	/** Translate `key`, substituting {name} placeholders from `params`. */
	function t(key, params) {
		var table = DICT[LANG] || DICT.en;
		var s = table[key];
		if (s === undefined) s = DICT.en[key];
		if (s === undefined) return key;
		if (!params) return s;
		return s.replace(/\{(\w+)\}/g, function (m, k) { return params[k] == null ? m : params[k]; });
	}

	function setLang(l) {
		if (LANGS.indexOf(l) < 0 || l === LANG) return;
		LANG = l;
		try { localStorage.setItem(STORE, l); } catch (e) {}
		listeners.slice().forEach(function (fn) { try { fn(l); } catch (e) {} });
	}
	function onChange(fn) { listeners.push(fn); }
	function langs() { return LANGS.slice(); }
	function label(l) { return l === 'vi' ? 'VI' : 'EN'; }

	try { var saved = localStorage.getItem(STORE); if (saved && LANGS.indexOf(saved) >= 0) LANG = saved; } catch (e) {}

	return { t: t, setLang: setLang, onChange: onChange, langs: langs, label: label, lang: function () { return LANG; } };
